class TimelineTests(StudioFixture):
    def test_long_duration_and_custom_frame_are_accepted(self):
        self.data['duration'] = 1800.0
        self.data['shots'][0]['end'] = 1800.0
        self.data['width'], self.data['height'] = 1080, 1920
        write_json(self.timeline, self.data)
        self.assertEqual(validate(self.timeline), [])

    def test_bad_numbers_frames_subtitles_gaps_and_fades_are_rejected(self):
        for label, mutate in [
            ('NaN', lambda data: data.update(duration=float('nan'))),
            ('boolean', lambda data: data.update(fps=True)),
            ('odd frame', lambda data: data.update(width=63)),
            ('gap', lambda data: data['shots'][0].update(start=0.2)),
            ('overlapping subtitles', lambda data: data['subtitles'].append({'start': 1.0, 'end': 2.0, 'text': 'Overlap'})),
            ('long fade', lambda data: data['audio_cues'][0].update(fade_in=4)),
            ('invalid offset', lambda data: data['audio_cues'][0].update(source_offset=float('inf'))),
            ('duck without voice', lambda data: data.update(narration_file=None)),
        ]:
            with self.subTest(label=label):
                data = copy.deepcopy(self.data)
                mutate(data)
                write_json(self.timeline, data)
                self.assertTrue(validate(self.timeline))

    def test_invalid_top_level_returns_errors(self):
        write_json(self.timeline, [])
        self.assertTrue(validate(self.timeline))


class AudioTests(StudioFixture):
    @unittest.skipUnless(importlib.util.find_spec('numpy'), 'numpy unavailable')
    def test_procedural_audio_is_repeatable_nonempty_stereo_and_peak_limited(self):
        for kind in ('wind', 'rain', 'hum', 'tone'):
            with self.subTest(kind=kind):
                first, _ = synthesize(kind, 0.2, 48000, 7, 220, -18)
                second, _ = synthesize(kind, 0.2, 48000, 7, 220, -18)
                self.assertEqual(first, second)
                values = array.array('h', first)
                self.assertEqual(len(values), 9600 * 2)
                self.assertGreater(max(map(abs, values)), 0)
                self.assertLessEqual(max(map(abs, values)), round(32767 * 10 ** (-18 / 20)))
                self.assertEqual(list(values[:2]), [0, 0])

    @unittest.skipUnless(importlib.util.find_spec('numpy'), 'numpy unavailable')
    def test_generator_writes_provenance_and_refuses_overwrite(self):
        output = self.base / 'generated.wav'
        self.command(ROOT / 'tools/generate_sound.py', '--kind', 'wind', '--duration', '0.2', '--output', output)
        self.assertAlmostEqual(probe_duration(output), 0.2)
        metadata = json.loads(output.with_suffix('.wav.json').read_text())
        self.assertEqual(metadata['file_sha256'], hashlib.sha256(output.read_bytes()).hexdigest())
        self.assertEqual(metadata['qa_status'], 'pending')
        before = output.read_bytes()
        self.command(ROOT / 'tools/generate_sound.py', '--kind', 'wind', '--duration', '0.2', '--output', output, success=False)
        self.assertEqual(output.read_bytes(), before)

    def test_mixer_dry_run_checks_real_inputs_and_places_ducked_loop(self):
        result = self.command(ROOT / 'tools/mix_audio.py', self.timeline, '--dry-run')
        plan = json.loads(result.stdout)
        self.assertFalse(plan['rendered'])
        self.assertIn('-stream_loop', plan['command'])
        graph = plan['command'][plan['command'].index('-filter_complex') + 1]
        self.assertIn('sidechaincompress', graph)
        self.assertIn('adelay=300.000000', graph)
        self.assertIn('afade=t=out:st=2.800000000', graph)
        self.assertFalse((self.part / 'audio/final_mix.wav').exists())

    def test_mixer_rejects_unverified_rights_missing_qa_changed_files_and_short_sources(self):
        for field, value in [('rights_status', 'unverified'), ('qa_status', 'pending'), ('sha256', '0' * 64)]:
            with self.subTest(field=field):
                registry = copy.deepcopy(self.asset_data)
                registry['assets']['AUD-001'][field] = value
                write_json(self.registry, registry)
                with self.assertRaises(ValueError):
                    build_mix(self.timeline)
        write_json(self.registry, self.asset_data)
        self.data['audio_cues'][0]['loop'] = False
        write_json(self.timeline, self.data)
        with self.assertRaisesRegex(ValueError, 'too short'):
            build_mix(self.timeline)

    def test_mixer_will_not_truncate_speech_or_overwrite_inputs(self):
        self.data['narration_start'] = 2.0
        write_json(self.timeline, self.data)
        with self.assertRaisesRegex(ValueError, 'Narration extends'):
            build_mix(self.timeline)
        self.data['narration_start'] = 0.3
        self.data['audio_file'] = self.data['narration_file']
        write_json(self.timeline, self.data)
        with self.assertRaisesRegex(ValueError, 'overwrite an input'):
            build_mix(self.timeline)

    def test_renderer_plan_uses_approved_frame_fps_and_mix(self):
        (self.part / 'images').mkdir()
        shutil.copy2(ROOT / 'references/style/visual-preferences/images/realistic-cinema.png',
                     self.part / 'images/shot_001.png')
        write_tone(self.part / 'audio/final_mix.wav', 3.0)
        output = self.base / 'rendered.mp4'
        result = self.command(ROOT / 'tools/render_part.py', self.timeline, '--output', output, '--dry-run')
        plan = json.loads(result.stdout)
        graph = plan['command'][plan['command'].index('-vf') + 1]
        self.assertIn('fps=24,scale=64:96', graph)
        self.assertIn('option framerate 24', plan['concat'])
        self.assertFalse(output.exists())

    @unittest.skipUnless(executable('ffmpeg'), 'FFmpeg not configured: actual mix/render integration unavailable')
    def test_real_ffmpeg_mix_and_render(self):
        (self.part / 'images').mkdir()
        shutil.copy2(ROOT / 'references/style/visual-preferences/images/realistic-cinema.png',
                     self.part / 'images/shot_001.png')
        self.command(ROOT / 'tools/mix_audio.py', self.timeline)
        self.assertAlmostEqual(probe_duration(self.part / 'audio/final_mix.wav'), 3.0)
        self.command(ROOT / 'tools/render_part.py', self.timeline, '--output', self.base / 'final.mp4')
        self.assertGreater((self.base / 'final.mp4').stat().st_size, 0)


